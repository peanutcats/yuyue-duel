'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const out = path.join(root, 'minigame');
const write = (name, data) => { const dest = path.join(out, name); fs.mkdirSync(path.dirname(dest), { recursive: true }); fs.writeFileSync(dest, data); };
const shared = ['core', 'roster', 'match', 'ai', 'practice', 'char', 'venues', 'render', 'scenes', 'campaign', 'knowledge', 'story', 'story-play', 'story-art', 'gameplay'];
const hashes = {};
for (const name of shared) {
  const data = fs.readFileSync(path.join(root, 'js', name + '.js'));
  write('shared/' + name + '.js', data); hashes[name] = crypto.createHash('sha256').update(data).digest('hex');
}
const network = fs.readFileSync(path.join(root, 'js/net.js'), 'utf8');
const start = network.indexOf('  const stamp ='), end = network.indexOf('  YY.GuestView = GuestView;');
if (start < 0 || end < start) throw new Error('GuestView source markers changed; update build-wechat.js');
const view = network.slice(start, end + '  YY.GuestView = GuestView;'.length).replaceAll('performance.now()', 'YY.platform.now()');
write('shared/net-view.js', `// Generated from js/net.js. Do not edit here.\n(function(G) { const YY = G.YY, KIND = ['over', 'side', 'under'];\n${view}\n})(typeof GameGlobal !== 'undefined' ? GameGlobal : globalThis);\n`);
write('assets/images/icon.png', fs.readFileSync(path.join(root, 'assets/icons/yuyue-wechat-icon.png')));
// Original layered Foley, rendered once at build time, not in the frame loop.
const sound = require('./sound-design');
const audioHashes = {};
for (const [name, effect] of Object.entries(sound.EFFECTS)) {
  const data = sound.wav(effect.samples);
  write('assets/audio/' + name + '.wav', data);
  audioHashes[name] = crypto.createHash('sha256').update(data).digest('hex');
}
write('src/audio-bank.js', "// Generated by tools/build-wechat.js from tools/sound-design.js.\n'use strict';\nmodule.exports = " + JSON.stringify(sound.manifest(), null, 2) + ';\n');
// Dialogue is loaded in chapter groups; speech never delays subtitles or inputs.
require('./story-voice-script');
const voiceManifestPath = path.join(root, 'assets/story/voice-manifest.json');
const allVoices = fs.existsSync(voiceManifestPath) ? JSON.parse(fs.readFileSync(voiceManifestPath, 'utf8')) : {};
const voiceScript=JSON.parse(fs.readFileSync(path.join(root,'assets/story/voice-script.json'),'utf8'));
// A release must contain every current line; missing speech is a build error.
const voices = Object.fromEntries(voiceScript.filter(row => allVoices[row.id]).map(row => [row.id, allVoices[row.id]]));
const unvoiced = voiceScript.length - Object.keys(voices).length;
if (unvoiced) throw Error(`${unvoiced} 条对白缺少配音，请先生成完整语音资源`);
write('src/voice-bank.js', "// Generated dialogue index.\n'use strict';\nmodule.exports = " + JSON.stringify(voices) + ';\n');
for (const item of Object.values(voices)) {
  if(!/^voice-[0-5]$/.test(item.root)||!/^v[0-9a-f]+\.mp3$/.test(item.file))throw Error('Invalid speech asset path');
  const data=fs.readFileSync(path.join(root, 'assets/story/voices', item.file));
  if(!item.engine||!item.sha256||crypto.createHash('sha256').update(data).digest('hex')!==item.sha256)throw Error('Speech provenance/hash missing or stale: '+item.file);
  write(item.root + '/' + item.file, data);
}
const voiceRoots = [...new Set(Object.values(voices).map(v => v.root))];
for(const name of ['voice-0','voice-1','voice-2','voice-3','voice-4','voice-5']) {
  const dir=path.join(out,name);if(!fs.existsSync(dir))continue;
  const keep=new Set(Object.values(voices).filter(v=>v.root===name).map(v=>v.file));
  for(const file of fs.readdirSync(dir))if(/^v[0-9a-f]+\.mp3$/.test(file)&&!keep.has(file))fs.rmSync(path.join(dir,file));
}
for (const name of voiceRoots) write(name + '/game.js', "// Speech resource subpackage.\n");
for(const name of ['README.md','KOKORO-LICENSE.txt']) {
 const file=path.join(root,'assets/story',name);if(fs.existsSync(file))write('assets/licenses/'+name,fs.readFileSync(file));
}
const gameConfig = JSON.parse(fs.readFileSync(path.join(out, 'game.json'), 'utf8'));
gameConfig.subpackages = voiceRoots.map(name => ({ name, root: name }));
write('game.json', JSON.stringify(gameConfig, null, 2) + '\n');
write('build-manifest.json', JSON.stringify({ appId: require('../minigame/config').appId, shared: hashes, audio: { sampleRate: sound.RATE, files: audioHashes }, voices: Object.keys(voices).length }, null, 2) + '\n');
function bytes(dir) { return fs.readdirSync(dir, { withFileTypes: true }).reduce((sum, entry) => sum + (entry.isDirectory() ? bytes(path.join(dir, entry.name)) : fs.statSync(path.join(dir, entry.name)).size), 0); }
const packages=Object.fromEntries(voiceRoots.map(name=>[name,bytes(path.join(out,name))]));
const total=bytes(out),main=total-Object.values(packages).reduce((a,b)=>a+b,0),MiB=1024*1024;
if(main>4*MiB||Object.values(packages).some(size=>size>4*MiB)||total>30*MiB)throw Error('Package budget exceeded; split speech/assets before shipping');
console.log(`微信工程已生成：${out}\nAppID: ${require('../minigame/config').appId}\n主包 ${(main/MiB).toFixed(2)} MiB；全部 ${(total/MiB).toFixed(2)} MiB；配音 ${Object.keys(voices).length} 条，${voiceRoots.length} 个分包`);
